const createMockItems = (equipmentIds: string[], days: number): RentalItem[] => {
  return equipmentIds.map((eqId, index) => {
    const equipment = mockEquipment.find(eq => eq.id === eqId) || mockEquipment[0];
    const cantidad = index === 0 ? 1 : Math.floor(Math.random() * 2) + 1;
    const subtotal = equipment.precioDia * cantidad * days;
    return {
      id: `item-${Date.now()}-${index}`,
      equipmentId: equipment.id,
      equipment,
      cantidad,
      tarifaTipo: 'DIA' as const,
      precioUnitario: equipment.precioDia,
      diasEstimados: days,
      deposito: equipment.depositoSugerido,
      subtotal,
    };
  });
};

const generateFolio = (index: number): string => {
  const year = new Date().getFullYear();
  return `ARR-${year}-${String(index + 1).padStart(4, '0')}`;
};

